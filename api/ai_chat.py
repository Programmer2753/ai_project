from fastapi import FastAPI
from pydantic import BaseModel
import google.generativeai as genai
import os

# Инициализация
api_key = os.getenv("GEMINI_API_KEY")
genai.configure(api_key=api_key)

# Выбираем стабильную и умную модель из твоего списка
MODEL_NAME = 'models/gemma-3-27b-it'

app = FastAPI()

model = genai.GenerativeModel(model_name=MODEL_NAME)

class AIRequest(BaseModel):
    message: str
    notes: list[str]
    history: list[dict]

@app.post("/api/ai_chat")
async def ai_chat(req: AIRequest):
    try:
        # Настраиваем "мозги" модели через системную инструкцию
        # Контекст из заметок
        system_rules = (
            "Ты — высокоинтеллектуальный адаптивный напарник, большая языковая модель, разработанная командой SelfNote. "
            "Твоя цель — быть полезным экспертом, который понимает пользователя с полуслова.\n\n"
            "ТВОИ ЖЕСТКИЕ ПРАВИЛА:\n"
            "1. ИДЕНТИЧНОСТЬ: На вопросы о твоем происхождении или о том, кто ты, отвечай: 'Я — большая языковая модель, разработанная командой SelfNote'. Не упоминай другие компании.\n"
            "2. ЯЗЫК: Всегда отвечай на том языке, на котором говорит пользователь (русский, украинский, английский и т.д.).\n"
            "3. ПРОФЕССИОНАЛЬНАЯ АДАПТИВНОСТЬ: Подстраивайся под темп и тон пользователя, но НЕ копируй сленг буквально. "
            "Если пользователь пишет 'йоу', не отвечай ему 'йоу'. Вместо этого ответь дружелюбно и неформально, но грамотно. "
            "Твой образ — современный, крутой ментор. Ты доступен в общении, но сохраняешь достоинство и интеллект. Избегай карикатурности и панибратства.\n"
            "4. ГЛУБИНА И ЭКСПЕРТНОСТЬ: Твои ответы должны быть аргументированными. Если в заметках пользователя есть информация по теме — используй её как фундамент. "
            "В любой математической или логической задаче рассуждай пошагово, чтобы исключить ошибки.\n"
            "5. ИНТУИЦИЯ: Игнорируй опечатки и понимай перевернутые слова (тевирп -> привет) мгновенно. Не трать время на уточнение очевидного, просто отвечай на суть вопроса."
        )

        history_text = ""
        for msg in req.history[:-1]: # Берем всё, кроме последнего (оно и так в message)
            role = "Пользователь" if msg['role'] == "user" else "Ты (SelfNote)"
            history_text += f"{role}: {msg['content']}\n"

        # В full_prompt добавим еще один акцент для модели
        context = "ЗАМЕТКИ ПОЛЬЗОВАТЕЛЯ:\n" + "\n".join(req.notes)
        user_prompt = f"### СИСТЕМНАЯ УСТАНОВКА:\n{system_rules}\n\n### КОНТЕКСТ:\n{context}\n\n### ПРЕДЫДУЩИЕ СООБЩЕНИЯ:\n{history_text}\n\n### СООБЩЕНИЕ ПОЛЬЗОВАТЕЛЯ:\n{req.message}\n\nТВОЙ АДАПТИВНЫЙ ОТВЕТ:"

        response = model.generate_content(user_prompt)
        
        if not response.text:
            return {"answer": "ИИ задумался и не выдал текст. Попробуй переформулировать."}
            
        return {"answer": response.text}
        
    except Exception as e:
        # Если вдруг опять 429 или 404, мы это увидим
        return {"answer": f"Произошла ошибка: {str(e)}"}