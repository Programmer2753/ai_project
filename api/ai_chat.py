from fastapi import FastAPI
from pydantic import BaseModel
import google.generativeai as genai
import os

# Инициализация
api_key = os.getenv("GEMINI_API_KEY")
genai.configure(api_key=api_key)

# Выбираем стабильную и умную модель из твоего списка
MODEL_NAME = 'models/gemma-3-27b-it'

app = FastAPI()

model = genai.GenerativeModel(model_name=MODEL_NAME)

class AIRequest(BaseModel):
    message: str
    notes: list[str]

@app.post("/api/ai_chat")
async def ai_chat(req: AIRequest):
    try:
        # Настраиваем "мозги" модели через системную инструкцию
        # Контекст из заметок
        system_rules = (
            "Ты — адаптивный и высокоинтеллектуальный ассистент с человечной манерой общения. "
            "ТВОИ ГЛАВНЫЕ ПРАВИЛА:\n"
            "1. ЯЗЫК: Отвечай строго на языке пользователя. Mirroring языка — приоритет.\n"
            "2. ЗЕРКАЛЬНОЕ ОТРАЖЕНИЕ СТИЛЯ: Это критически важно! Анализируй тон пользователя и подстраивайся под него. "
            "Если пользователь пишет неформально, использует сленг ('йоу', 'приветки', 'че как') — отвечай в том же расслабленном стиле. "
            "Если пользователь пишет официально или научно — будь серьезным и структурированным. Будь 'на одной волне' с собеседником.\n"
            "3. ИНТЕЛЛЕКТ БЕЗ ЗАНУДСТВА: Твои ответы должны быть глубокими по сути, но естественными по форме. "
            "Избегай шаблонных фраз вроде 'Чем я могу вам помочь?'. Если ответ требует логики — давай её, но не читай лекции.\n"
            "4. ИНТУИЦИЯ: Понимай опечатки, сокращения и перевернутые слова (тевирп -> привет) мгновенно. "
            "Не переспрашивай, а просто подхватывай диалог, как будто всё написано правильно."
        )

        # В full_prompt добавим еще один акцент для модели
        context = "ЗАМЕТКИ ПОЛЬЗОВАТЕЛЯ:\n" + "\n".join(req.notes)
        user_prompt = f"### СИСТЕМНАЯ УСТАНОВКА:\n{system_rules}\n\n### КОНТЕКСТ:\n{context}\n\n### СООБЩЕНИЕ ПОЛЬЗОВАТЕЛЯ:\n{req.message}\n\nТВОЙ АДАПТИВНЫЙ ОТВЕТ:"

        response = model.generate_content(user_prompt)
        
        if not response.text:
            return {"answer": "ИИ задумался и не выдал текст. Попробуй переформулировать."}
            
        return {"answer": response.text}
        
    except Exception as e:
        # Если вдруг опять 429 или 404, мы это увидим
        return {"answer": f"Произошла ошибка: {str(e)}"}